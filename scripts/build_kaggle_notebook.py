                "                        cb[\"marker_pos\"].to(device),\n",
                "                        cb[\"marker_mask\"].to(device),\n",
                "                        cb[\"qtype\"].to(device)\n",
                "                    )\n",
                "                l_np = l_sub.float().cpu().numpy()\n",
                "                for r, it in enumerate(c_chunk):\n",
                "                    k = len(it[\"markers\"])\n",
